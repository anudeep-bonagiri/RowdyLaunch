// Renders the Apple Wallet pass artwork from the site's own images and
// writes it as base64 into lib/passAssets.ts, so the serverless function
// needs no filesystem. Run: node scripts/pass-assets.mjs
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const out = {};
const put = async (name, buf) => { out[name] = buf.toString("base64"); };

// icon: square, 29pt
for (const [suffix, px] of [["", 29], ["@2x", 58], ["@3x", 87]]) {
  await put(`icon${suffix}.png`, await sharp("public/icon-192.png").resize(px, px).png().toBuffer());
}
// logo: up to 160x50pt; the rocket-rider mark, square
for (const [suffix, px] of [["", 50], ["@2x", 100], ["@3x", 150]]) {
  await put(`logo${suffix}.png`, await sharp("public/logo.png").resize(px, px, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer());
}
// thumbnail: up to 90x90pt; the sprinting mascot, kept transparent
for (const [suffix, w, h] of [["", 90, 58], ["@2x", 180, 116], ["@3x", 270, 174]]) {
  await put(`thumbnail${suffix}.png`, await sharp("public/mascot.png").resize(w, h, { fit: "inside" }).png().toBuffer());
}

const ts = `// Generated by scripts/pass-assets.mjs. Do not edit by hand.\nexport const passAssets: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync("lib/passAssets.ts", ts);
console.log(Object.entries(out).map(([k, v]) => `${k} ${Math.round(v.length * 0.75 / 1024)}KB`).join(", "));
